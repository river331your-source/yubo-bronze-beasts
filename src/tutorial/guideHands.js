export function drawGuideHand(canvas, kind) {
  const ctx = canvas?.getContext('2d');
  if (!ctx) return;
  const W = canvas.width;
  const H = canvas.height;
  ctx.clearRect(0, 0, W, H);
  const draw = (pose, dx) => {
    ctx.save();
    ctx.lineWidth = 2;
    ctx.strokeStyle = 'rgba(201,168,76,.9)';
    ctx.beginPath();
    for (const [a, b] of BONES) {
      ctx.moveTo(pose[a][0] * W + dx, pose[a][1] * H);
      ctx.lineTo(pose[b][0] * W + dx, pose[b][1] * H);
    }
    ctx.stroke();
    ctx.fillStyle = '#7fd4a8';
    for (const p of pose) {
      ctx.beginPath();
      ctx.arc(p[0] * W + dx, p[1] * H, 3, 0, Math.PI * 2);
      ctx.fill();
    }
    ctx.restore();
  };
  if (kind === 'clap') {
    draw(POSES.dissolve, -22);
    draw(POSES.dissolve.map((p) => [1 - p[0], p[1]]), 22);
  } else {
    draw(POSES[kind] ?? POSES.fist, 0);
  }
}
